// Writes app/config.js and admin/config.js from supabase.config.json (or env vars).
// Used by the GitHub Pages and Android builds, and by `npm run config` locally.
//   SUPABASE_URL / SUPABASE_ANON_KEY override the file; APP_URL is the public web-app link used in shares.
import { readFileSync, writeFileSync } from 'node:fs';

const file = JSON.parse(readFileSync(new URL('../supabase.config.json', import.meta.url), 'utf8'));
const supabaseUrl = (process.env.SUPABASE_URL || file.supabaseUrl || '').replace(/\/$/, '');
const supabaseAnonKey = process.env.SUPABASE_ANON_KEY || file.supabaseAnonKey || '';
const appUrl = process.env.APP_URL || file.appUrl || '';
if (supabaseUrl && !/^https:\/\/[a-z0-9-]+\.supabase\.(co|in)$|^https:\/\//.test(supabaseUrl)) throw new Error('supabaseUrl must be https');
if (/service_role/.test(Buffer.from((supabaseAnonKey.split('.')[1] || ''), 'base64').toString())) throw new Error('That is the service_role key — use the anon (public) key.');
const cfg = { supabaseUrl, supabaseAnonKey, appUrl };
const body = (where) => `// Generated by scripts/write-config.mjs for ${where}. The anon key is public by design.\nwindow.PKO_CONFIG = ${JSON.stringify(cfg, null, 2)};\n`;
writeFileSync(new URL('../app/config.js', import.meta.url), body('the member app'));
writeFileSync(new URL('../admin/config.js', import.meta.url), body('the dashboard'));
console.log(supabaseUrl ? `Config written for ${supabaseUrl}` : 'Config written WITHOUT a Supabase project (set supabase.config.json).');
